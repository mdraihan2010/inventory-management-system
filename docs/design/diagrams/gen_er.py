# Generates er-diagram.dot: the real MongoDB collections of StockPilot (server/src/models)
F = 'Latin Modern Roman,10 Regular'
FM = 'Latin Modern Mono,LM Mono 10'
# field: (name, type, key) key: PK, FK->collection, U (unique), E (embedded row)
C = {
 'users': [('_id','ObjectId','PK'),('name','String',''),('email','String','U'),('passwordHash','String',''),('role','String (enum)',''),('isActive','Boolean',''),('mustChangePassword','Boolean','')],
 'categories': [('_id','ObjectId','PK'),('name','String','U'),('description','String',''),('isActive','Boolean','')],
 'brands': [('_id','ObjectId','PK'),('name','String','U'),('description','String',''),('isActive','Boolean','')],
 'products': [('_id','ObjectId','PK'),('name','String',''),('sku','String','U'),('barcode','String','U'),('category','ObjectId','FK:categories'),('brand','ObjectId','FK:brands'),
              ('purchasePrice','Number',''),('sellingPrice','Number',''),('currentStock','Number',''),('minStockLevel','Number',''),('unit','String',''),('isActive','Boolean','')],
 'customers': [('_id','ObjectId','PK'),('name','String',''),('phone','String',''),('email','String','U'),('address','String',''),('notes','String',''),('isActive','Boolean','')],
 'suppliers': [('_id','ObjectId','PK'),('name','String',''),('companyName','String',''),('phone','String',''),('email','String','U'),('address','String',''),('isActive','Boolean','')],
 'sales': [('_id','ObjectId','PK'),('saleNumber','String','U'),('customer','ObjectId | null','FK:customers'),('saleDate','Date',''),
           ('items[]','Array','E'),('  product','ObjectId','FK:products'),('  productName, sku','String','E'),('  quantity, unitPrice','Number','E'),('  lineTotal, costPrice','Number','E'),
           ('subtotal, discount','Number',''),('grandTotal','Number',''),('paidAmount','Number',''),('outstandingAmount','Number',''),('returnedAmount','Number',''),
           ('paymentStatus','String (enum)',''),('status','String (enum)',''),('walkInPaymentMethod','String',''),('createdBy','ObjectId','FK:users')],
 'purchases': [('_id','ObjectId','PK'),('purchaseNumber','String','U'),('supplier','ObjectId','FK:suppliers'),('purchaseDate','Date',''),
               ('items[]','Array','E'),('  product','ObjectId','FK:products'),('  productName, sku','String','E'),('  quantity, unitPrice','Number','E'),('  lineTotal','Number','E'),
               ('subtotal, discount','Number',''),('grandTotal','Number',''),('paidAmount','Number',''),('returnedAmount','Number',''),('status','String (enum)',''),('createdBy','ObjectId','FK:users')],
 'payments': [('_id','ObjectId','PK'),('sale','ObjectId','FK:sales'),('customer','ObjectId | null','FK:customers'),('amount','Number',''),('method','String (enum)',''),('reference','String',''),('createdBy','ObjectId','FK:users')],
 'supplierpayments': [('_id','ObjectId','PK'),('purchase','ObjectId','FK:purchases'),('supplier','ObjectId','FK:suppliers'),('amount','Number',''),('method','String (enum)',''),('reference','String',''),('createdBy','ObjectId','FK:users')],
 'returns': [('_id','ObjectId','PK'),('returnNumber','String','U'),('kind','CUSTOMER | SUPPLIER',''),('sale','ObjectId | null','FK:sales'),('purchase','ObjectId | null','FK:purchases'),
             ('customer','ObjectId | null','FK:customers'),('supplier','ObjectId | null','FK:suppliers'),
             ('items[]','Array','E'),('  product','ObjectId','FK:products'),('  quantity, unitPrice','Number','E'),('  lineTotal, costPrice','Number','E'),
             ('totalValue','Number',''),('creditApplied','Number',''),('cashRefund','Number',''),('refundMethod','String',''),('reason','String',''),
             ('status','ACTIVE | CANCELLED',''),('cancelledBy','ObjectId | null','FK:users'),('createdBy','ObjectId','FK:users')],
 'stockmovements': [('_id','ObjectId','PK'),('product','ObjectId','FK:products'),('type','String (enum)',''),('change','Number',''),('previousStock','Number',''),('resultingStock','Number',''),('reason','String',''),('createdBy','ObjectId','FK:users')],
 'auditlogs': [('_id','ObjectId','PK'),('user','ObjectId','FK:users'),('action','String',''),('entityType','String',''),('entityId','String',''),('summary','String','')],
}
def esc(t): return t.replace('&','&amp;').replace('<','&lt;').replace('>','&gt;')
out = ['// Database (ER) Diagram: StockPilot MongoDB collections. Generated by gen_er.py from server/src/models',
       '// Render: dot -Tpdf er-diagram.dot -o er-diagram.pdf',
       'digraph ER {',
       f'  graph [rankdir=LR, fontname="{F}", nodesep=0.35, ranksep=1.1, splines=spline, pad=0.25, ranksep=1.3, concentrate=false];',
       f'  node [shape=plain, fontname="{F}", fontsize=10];',
       f'  edge [fontname="{F}", fontsize=9, arrowsize=0.9, penwidth=0.9];']
edges = []
for coll, fields in C.items():
    rows = [f'<TR><TD COLSPAN="3" BGCOLOR="#2f4a7a"><FONT COLOR="white"><B>{coll}</B></FONT></TD></TR>']
    for i,(n,t,k) in enumerate(fields):
        emb = n.startswith('  ') or k=='E' and not n.startswith('items')
        name = esc(n.strip())
        if n.startswith('  '): name = '&nbsp;&nbsp;&nbsp;&#8627; ' + name
        key = 'PK' if k=='PK' else ('FK' if k.startswith('FK') else ('UQ' if k=='U' else ''))
        bg = ' BGCOLOR="#f4f4f4"' if (n.startswith('  ') or n=='items[]') else ''
        nm = f'<B>{name}</B>' if k=='PK' else (f'<I>{name}</I>' if n.startswith('  ') or n=='items[]' else name)
        port = f' PORT="p{i}"'
        keycell = f'<FONT POINT-SIZE="8" COLOR="#555555">{key}</FONT>' if key else ' '
        is_audit = n.strip() in ('createdBy', 'cancelledBy')
        ttext = esc(t) + (' &#8594; users' if is_audit else '')
        pk_port = ' PORT="pk"' if k=='PK' else ''
        fk_port = f' PORT="f{i}"' if k.startswith('FK') and not is_audit else ''
        rows.append(f'<TR><TD ALIGN="LEFT"{bg}{pk_port}>{keycell}</TD>'
                    f'<TD ALIGN="LEFT"{bg}>{nm}</TD><TD ALIGN="LEFT"{bg}{fk_port}><FONT FACE="{FM}" POINT-SIZE="8.5">{ttext}</FONT></TD></TR>')
        if k.startswith('FK'):
            tgt = k.split(':')[1]
            optional = 'null' in t
            edges.append((coll, i, tgt, optional, n.strip()=='createdBy' or n.strip()=='cancelledBy'))
    out.append(f'  {coll} [label=<<TABLE BORDER="1" CELLBORDER="0" CELLSPACING="0" CELLPADDING="3" COLOR="#2f4a7a">' + ''.join(rows) + '</TABLE>>];')
for coll,i,tgt,opt,audit in edges:
    if audit:
        continue  # createdBy / cancelledBy are written as "-> users" in the row, to keep the picture readable
    # many (crow) on the referencing side, one (bar) or zero-or-one (bar + circle) on the referenced side
    head = 'teeodot' if opt else 'teetee'
    out.append(f'  {coll}:f{i}:e -> {tgt}:pk:w [dir=both, arrowtail=crowodot, arrowhead={head}, color="#222222"];')
out.append('  legend [shape=plain, label=<<TABLE BORDER="1" CELLBORDER="0" CELLSPACING="0" CELLPADDING="4" COLOR="#888888">'
           '<TR><TD ALIGN="LEFT"><B>How to read</B></TD></TR>'
           '<TR><TD ALIGN="LEFT">PK = primary key (_id), FK = reference to another collection, UQ = unique</TD></TR>'
           '<TR><TD ALIGN="LEFT">&#8627; rows in grey are stored inside the document (embedded items array)</TD></TR>'
           '<TR><TD ALIGN="LEFT">Crow foot = many; bar = exactly one; bar + circle = zero or one</TD></TR>'
           '<TR><TD ALIGN="LEFT">createdBy / cancelledBy point to users (who did it); lines left out for clarity</TD></TR>'
           '<TR><TD ALIGN="LEFT">Every collection also has createdAt and updatedAt (Mongoose timestamps)</TD></TR>'
           '</TABLE>>];')
out.append('}')
open('er-diagram.dot','w').write('\n'.join(out)+'\n')
print(len(edges),'references')
